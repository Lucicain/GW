    def test_installed_native_startup_boundary(self):
        game=Path('D:/steam/steamapps/common/Mount & Blade II Bannerlord')
        live=game/'Modules/GreyWarden/bin/Win64_Shipping_Client'
        preflight=ROOT/'tools/Invoke-ModuleLoadPreflight.ps1'
        # Recreate the failing native patch point in an isolated assembly. This
        # uses the real installed target, Harmony and .NET Framework loader,
        # rather than a mock CampaignUIHelper initialized at a convenient time.
        with tempfile.TemporaryDirectory(prefix='gwp-nameplate-startup-') as directory:
            p=Path(directory)
            refs={'0Harmony':live/'0Harmony.dll',
                  'SandBox.ViewModelCollection':game/'Modules/SandBox/bin/Win64_Shipping_Client/SandBox.ViewModelCollection.dll',
                  'TaleWorlds.Library':game/'bin/Win64_Shipping_Client/TaleWorlds.Library.dll'}
            reference_xml=''.join(f'<Reference Include="{name}"><HintPath>{str(path).replace("&","&amp;")}</HintPath></Reference>' for name,path in refs.items())
            (p/'Probe.csproj').write_text('<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup><TargetFramework>net472</TargetFramework><AssemblyName>UnsafeNameplateProbe</AssemblyName></PropertyGroup><ItemGroup>'+reference_xml+'</ItemGroup></Project>',encoding='utf-8')
            (p/'Probe.cs').write_text('using HarmonyLib;using SandBox.ViewModelCollection.Nameplate;[HarmonyPatch(typeof(PartyNameplateVM),"RefreshBinding")]static class UnsafeNameplateProbe{static void Postfix(){}}',encoding='utf-8')
            build=subprocess.run(['dotnet','build',str(p/'Probe.csproj'),'-c','Release','-v','quiet'],capture_output=True,text=True,timeout=90)
            self.assertEqual(0,build.returncode,build.stdout+build.stderr)
            old_dll=p/'bin/Release/net472/UnsafeNameplateProbe.dll'
            negative=subprocess.run(['powershell','-NoProfile','-File',str(preflight),'-ModuleDll',str(old_dll)],capture_output=True,text=True,timeout=90)
            self.assertNotEqual(0,negative.returncode,negative.stdout+negative.stderr)
            self.assertIn('EARLY_UI_FIELD_FAIL RefreshBinding -> CampaignUIHelper.',negative.stdout)
            self.assertIn('PREFLIGHT=FAIL',negative.stdout)
        positive=subprocess.run(['powershell','-NoProfile','-File',str(preflight)],capture_output=True,text=True,timeout=90)
        self.assertEqual(0,positive.returncode,positive.stdout+positive.stderr)
        self.assertIn('EARLY_UI_FIELD_FAIL_COUNT=0',positive.stdout)
        self.assertIn('STATIC_INIT_FAIL_COUNT=0',positive.stdout)
        self.assertIn('PREFLIGHT=PASS',positive.stdout)
        print('NAMEPLATE_STARTUP_NATIVE: legacy RefreshBinding dependency rejected; installed property-setter patches PASS; no game launched')

