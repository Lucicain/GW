"""Decompile the installed Bannerlord into a fixed, indexed vanilla-source library.

Until 2026-10-28 every agent decompiled the DLL it happened to need into
.codex_tmp/ (nine overlapping *-decomp folders, 1.5 GB of scratch), read a
fragment, and kept only a one-line rule. Nothing it learned about the base game
survived the session. This library is the permanent copy every agent queries
instead, with the same CodeGraph tool it uses on our own code (user ruling
2026-10-28).

Layout (outside the repository, never hand-edited, never committed):

  <out>/<version>/managed/<Assembly>/<Namespace>/<Type>.cs   ilspycmd -p output
  <out>/<version>/moduledata/<Module>/...                     official XML, English only
  <out>/<version>/manifest.json                               DLL hashes it was built from
  <out>/<version>/.codegraph/                                 index for codegraph_explore

A game update gets a new version folder; delete the old one once nothing cites
it. Run again after an update — a version whose DLL hashes still match is left
alone.
"""
from __future__ import annotations

import argparse
import concurrent.futures
import hashlib
import json
import re
import shutil
import struct
import subprocess
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_GAME = Path(r"D:\steam\steamapps\common\Mount & Blade II Bannerlord")
DEFAULT_OUT = ROOT.parent / "BannerlordSource"

# Single-player official modules. Multiplayer and third-party mods stay out:
# they are not the game our mod runs against.
MODULES = ("Native", "SandBoxCore", "SandBox", "StoryMode", "CustomBattle", "BirthAndDeath", "NavalDLC")
# Generated Gauntlet widget bindings are tens of thousands of lines of UI
# boilerplate that answer no behaviour question.
SKIP_DLL = re.compile(r"GauntletUI\.AutoGenerated|Multiplayer", re.I)


def game_version(game: Path) -> str:
    text = (game / "bin/Win64_Shipping_Client/Version.xml").read_text(encoding="utf-8")
    return re.search(r'Singleplayer Value="([^"]+)"', text).group(1)


def is_managed(dll: Path) -> bool:
    # A .NET assembly has a non-empty CLI header (data directory 14). The
    # engine itself, TaleWorlds.Native.dll, is C++: disassemble it instead
    # (docs/reference/investigation-methods.md).
    data = dll.read_bytes()
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    optional = pe + 24
    directories = optional + (96 if struct.unpack_from("<H", data, optional)[0] == 0x10B else 112)
    rva, size = struct.unpack_from("<II", data, directories + 14 * 8)
    return size > 0


def managed_dlls(game: Path) -> list[Path]:
    dlls = sorted((game / "bin/Win64_Shipping_Client").glob("TaleWorlds.*.dll"))
    for module in MODULES:
        dlls += sorted((game / "Modules" / module / "bin/Win64_Shipping_Client").glob("*.dll"))
    return [d for d in dlls if not SKIP_DLL.search(d.name) and is_managed(d)]


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def decompile(dll: Path, managed: Path) -> str:
    target = managed / dll.stem
    result = subprocess.run(["ilspycmd", "-p", "-o", str(target), str(dll)], capture_output=True, text=True)
    if result.returncode:
        return f"{dll.name}: {result.stderr.strip()[:300]}"
    return ""


def copy_moduledata(game: Path, dest: Path) -> int:
    count = 0
    for module in MODULES:
        source = game / "Modules" / module
        files = [source / "SubModule.xml"] if (source / "SubModule.xml").exists() else []
        files += [p for p in (source / "ModuleData").rglob("*.xml")
                  # Languages/<code>/ holds translations; the English strings sit directly in Languages/.
                  if "Languages" not in p.relative_to(source).parts[:-2]]
        for path in files:
            target = dest / module / path.relative_to(source)
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(path, target)
            count += 1
    return count


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--game", type=Path, default=DEFAULT_GAME)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--jobs", type=int, default=4)
    args = parser.parse_args()

    # codegraph ships as a .cmd shim, which CreateProcess only finds by full name.
    codegraph = shutil.which("codegraph")
    if codegraph is None:
        print("codegraph is not on PATH; the library would be built without its index.", file=sys.stderr)
        return 1

    version = game_version(args.game)
    final = args.out / version
    dlls = managed_dlls(args.game)
    hashes = {d.name: sha256(d) for d in dlls}

    manifest_path = final / "manifest.json"
    if manifest_path.exists() and json.loads(manifest_path.read_text(encoding="utf-8")).get("dlls") == hashes:
        if (final / ".codegraph").exists():
            print(f"{final} already matches the installed {version}; nothing to do.")
            return 0
        return build_index(codegraph, final)

    staging = args.out / f"{version}.building"
    shutil.rmtree(staging, ignore_errors=True)
    managed = staging / "managed"
    managed.mkdir(parents=True)

    with concurrent.futures.ThreadPoolExecutor(args.jobs) as pool:
        failures = [f for f in pool.map(lambda d: decompile(d, managed), dlls) if f]
    if failures:
        print("Decompilation failed:\n" + "\n".join(failures), file=sys.stderr)
        return 1
    xml = copy_moduledata(args.game, staging / "moduledata")

    (staging / "manifest.json").write_text(json.dumps({
        "version": version,
        "built": date.today().isoformat(),
        "game": str(args.game),
        "modules": MODULES,
        "dlls": hashes,
    }, indent=1), encoding="utf-8")

    # Move the old library aside before deleting it: a CodeGraph process
    # holding its index open makes the rename fail loudly here, instead of a
    # half-deleted library that the next rename then cannot replace.
    if final.exists():
        retired = args.out / f"{version}.retired"
        shutil.rmtree(retired, ignore_errors=True)
        final.rename(retired)
        staging.rename(final)
        shutil.rmtree(retired)
    else:
        staging.rename(final)
    print(f"Decompiled {len(dlls)} assemblies and copied {xml} XML files into {final}")
    return build_index(codegraph, final)


def build_index(codegraph: str, final: Path) -> int:
    index = subprocess.run([codegraph, "init", "-y", str(final)], capture_output=True, text=True)
    print(index.stdout.strip()[-600:])
    if index.returncode:
        print(index.stderr.strip()[-600:], file=sys.stderr)
        return 1
    return 0

if __name__ == "__main__":
    sys.exit(main())
