#!/usr/bin/env python3
"""Generate compiled text constants and native XML from the bilingual text source."""
import argparse
import html
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
MODULE = ROOT / "GreyWardenPolicePurity"
TEXT = MODULE / "PlayerText"
CATALOG = MODULE / "GwpTextCatalog.g.cs"
CN = MODULE / "_Module/ModuleData/Languages/CNs/std_gwp_strings_xml-zho-CN.xml"
REFERENCE = re.compile(r"GwpTextCatalog\.(gwp_\w+|English_gwp_\w+|Raw_\w+)")
INLINE = re.compile(r'"\{=(gwp_[A-Za-z0-9_]+)\}')


def read(path):
    return path.read_bytes().decode("utf-8-sig").replace("\r\n", "\n")


def xml_escape(value):
    return html.escape(value, quote=True).replace("&#x27;", "&apos;").replace("\n", "&#10;")


def variables(value):
    return set(re.findall(r"\{[A-Z][A-Z_0-9.]*\}", value or ""))


def generate(check):
    data = json.loads((TEXT / "strings.json").read_text(encoding="utf-8"))
    entries = data["strings"]
    refs = set()
    locations = {key: [] for key in entries}
    for path in sorted(MODULE.glob("*.cs")):
        if path == CATALOG:
            continue
        source = read(path)
        inline = INLINE.findall(source)
        if inline:
            raise ValueError(f"Inline player text in {path.name}: {inline}")
        for match in REFERENCE.finditer(source):
            name = match[1]
            refs.add(name)
            key = name.removeprefix("English_")
            if key in locations:
                locations[key].append(f"{path.name}:{source.count(chr(10), 0, match.start()) + 1}")

    lines = ["// <auto-generated />", "// Edit PlayerText/strings.json; run python tools/Generate-PlayerText.py.",
             "namespace GreyWardenPolicePurity", "{", "    internal static class GwpTextCatalog", "    {"]
    for name in sorted(refs):
        if name.startswith("Raw_"):
            value = data["fragments"][name[4:]]
        else:
            key = name.removeprefix("English_")
            english = entries[key]["en"]
            if english is None:
                raise ValueError(f"Missing English for referenced text: {key}")
            value = english if name.startswith("English_") else "{=" + key + "}" + english
        lines.append(f"        internal const string {name} = {json.dumps(value, ensure_ascii=False)};")
    lines += ["    }", "}", ""]
    outputs = {CATALOG: "\n".join(lines)}

    language = read(CN)
    chinese = "\n".join(f'  <string id="{key}" text="{xml_escape(entry["zh"])}" />'
                        for key, entry in entries.items())
    language, count = re.subn(r"(?<=<strings>).*?(?=</strings>)",
                             lambda _: "\n" + chinese + "\n", language, flags=re.S)
    if count != 1:
        raise ValueError("Expected one Chinese strings container")
    outputs[CN] = language

    for path in sorted((MODULE / "_Module").rglob("*.xml")):
        if "Languages" in path.parts:
            continue

        def english_xml(match):
            key = match[2]
            if key not in entries:
                return match[0]
            value = entries[key]["en"]
            if value is None:
                raise ValueError(f"Missing English for XML text: {key}")
            locations[key].append(path.relative_to(MODULE).as_posix())
            return match[1] + xml_escape(value)

        old = read(path)
        new = re.sub(r'(\{=(gwp_[A-Za-z0-9_]+)\})[^"<]*', english_xml, old)
        outputs[path] = new

    index = ["# 玩家词句索引（生成）", "", "编辑 `strings.json`，本表仅供查找。", "",
             "| 文本键 | 英文 | 中文 | 出现位置或情境 |", "|---|---|---|---|"]
    for key, entry in entries.items():
        if entry["en"] is not None and variables(entry["en"]) != variables(entry["zh"]):
            raise ValueError(f"Chinese/English placeholders differ: {key}")
        context = entry.get("context") or ", ".join(dict.fromkeys(locations[key])) or "未检出直接引用；保留"
        cells = [key, entry["en"] or "—", entry["zh"], context]
        index.append("| " + " | ".join(v.replace("|", "&#124;").replace("\n", "<br>") for v in cells) + " |")
    outputs[TEXT / "index.md"] = "\n".join(index) + "\n"

    changed = []
    for path, expected in outputs.items():
        current = read(path) if path.exists() else None
        if current == expected:
            continue
        changed.append(path.relative_to(ROOT).as_posix())
        if not check:
            original = path.read_bytes() if path.exists() else b""
            newline = "\r\n" if b"\r\n" in original else "\n"
            encoded = expected.replace("\n", newline).encode("utf-8")
            if original.startswith(b"\xef\xbb\xbf"):
                encoded = b"\xef\xbb\xbf" + encoded
            path.write_bytes(encoded)
    if check and changed:
        print("PLAYER TEXT: STALE\n" + "\n".join(changed))
        return 1
    print(f"PLAYER TEXT: PASS ({len(entries)} bilingual entries, {len(refs)} compiled constants, {len(changed)} updated)")
    return 0


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    sys.exit(generate(parser.parse_args().check))
